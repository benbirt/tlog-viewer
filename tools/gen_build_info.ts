// Writes a JS module saying which commit the site was built from (see
// build_info.d.ts). Bazel provides that only to stamped builds, made with
// --config=release; any other build is marked as a development build.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const REPO = "https://github.com/benbirt/tlog-viewer";

let commit: string | null = null;
let dirty = false;
const statusFile = process.env.BAZEL_STABLE_STATUS_FILE;
if (statusFile) {
  const status = new Map(readFileSync(join(process.env.JS_BINARY__EXECROOT ?? "", statusFile), "utf8")
    .split("\n").filter((l) => l.includes(" ")).map((l): [string, string] => {
      const i = l.indexOf(" ");
      return [l.slice(0, i), l.slice(i + 1)];
    }));
  const stamped = status.get("STABLE_GIT_COMMIT") ?? "";
  if (!/^[0-9a-f]{40}$/.test(stamped)) throw new Error("stamped build without STABLE_GIT_COMMIT; is --workspace_status_command set?");
  commit = stamped;
  dirty = status.get("STABLE_GIT_DIRTY") === "true";
}

process.stdout.write(`// Generated by //:build_info. Do not edit.
export const BUILD = ${JSON.stringify({ repo: REPO, commit, dirty })};
`);
