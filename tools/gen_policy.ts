// Usage: gen_policy <policy file> <MODULE.bazel> <verifier.wasm> <wasm_exec.js>
// Writes a JS module embedding the policy to stdout (see policy_data.d.ts).
//
// The policy is updated and deployed without review, so it is read here, at
// build time, by the same verifier the page will read it with: a policy that
// would fail in every reader's browser fails the build instead.
import { readFileSync } from "node:fs";
import { verifierOver } from "../web/js/verifier.js";
import { loadWasm } from "./wasm.js";

const [policyPath, modulePath, wasm, exec] = process.argv.slice(2);
if (!policyPath || !modulePath || !wasm || !exec) throw new Error("usage: gen_policy <policy file> <MODULE.bazel> <verifier.wasm> <wasm_exec.js>");
const text = readFileSync(policyPath, "utf8");

const policy = await verifierOver(await loadWasm(wasm, exec)).policy(text);
if (policy.origins.length === 0) throw new Error("policy trusts no logs");

const override = /git_override\(\s*module_name = "google-tlog-witness",[^)]*\)/.exec(readFileSync(modulePath, "utf8"));
const commit = override && /commit = "([0-9a-f]{40})"/.exec(override[0])?.[1];
if (!commit) throw new Error("cannot find the google-tlog-witness commit in MODULE.bazel");

const source = {
  repo: "https://github.com/google/google-tlog-witness",
  commit,
  target: "//policies/paic:prod-verifier",
};
// The verifier's runtime never lets Node's event loop empty, so leave once the output is written.
process.stdout.write(`// Generated by //:policy_data. Do not edit.
export const POLICY_TEXT = ${JSON.stringify(text)};
export const POLICY_SOURCE = ${JSON.stringify(source)};
`, () => process.exit(0));
